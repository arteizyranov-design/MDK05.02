<h2>Задача 5:</h2>

<p>Вывести на экран «прямоугольник», образованный из двух видов символов. Контур прямоугольника должен состоять из одного символа, а в «заливка» — из другого. Даны размеры прямоугольника а и в.</p>
<?php
$a = 7; // Ширина
$b = 5; // Высота

$borderChar = "X"; // Символ контура
$fillChar = "O";   // Символ заливки

for ($i = 0; $i < $b; $i++) {
    for ($j = 0; $j < $a; $j++) {
        // Если это первая строка, последняя строка, первый столбец или последний столбец
        if ($i == 0 || $i == $b - 1 || $j == 0 || $j == $a - 1) {
            echo $borderChar;
        } else {
            echo $fillChar;
        }
    }
    echo "<br>";
}
?>

