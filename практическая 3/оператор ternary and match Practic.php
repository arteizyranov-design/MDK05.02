<h2>Задача 4:</h2>
<p>Для целого числа к от 1 до 99 напечатать фразу «Мне к лет», 
учитывая при этом, что при некоторых значениях к слово «лет» надо заменить на слово «год» или «года». Например, 11 лет, 22 года, 51 год</p>
<?php
$k = 22;

$word = match(true) {
    $k % 100 >= 11 && $k % 100 <= 14 => "лет",
    $k % 10 == 1 => "год",
    $k % 10 >= 2 && $k % 10 <= 4 => "года",
    default => "лет"
};

print("Мне $k $word");
?>
