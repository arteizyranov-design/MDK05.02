Сделать функцию для нахождения всех делителей заданного числа. Функция должна вернуть массив с делителями.
<?php
function getDivisors(int $num): array {
    $divisors = [];
    $sqrt = (int) sqrt($num);

    for ($i = 1; $i <= $sqrt; $i++) {
        if ($num % $i === 0) {
            $divisors[] = $i;
            // Добавляем парный делитель, если он отличается от $i
            if ($i !== intdiv($num, $i)) {
                $divisors[] = intdiv($num, $i);
            }
        }
    }

    sort($divisors);
    return $divisors;
}
print_r(getDivisors(36));
?>

