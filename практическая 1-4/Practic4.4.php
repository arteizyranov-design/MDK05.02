Функция принимает массив чисел. Сделайте так, чтобы она возвращала сумму квадратов этих чисел.
<?php
function sumOfSquares(array $numbers): int|float {
    $sum = 0;
    foreach ($numbers as $num) {
        $sum += $num * $num;
    }
    return $sum;
}
