$brick = [$x, $y, $z];
sort($brick); // $brick[0] <= $brick[1] <= $brick[2]

// Сортируем размеры отверстия по возрастанию
$hole = [$A, $B];
sort($hole);  // $hole[0] <= $hole[1]

// Кирпич пройдёт, если две его наименьшие стороны меньше сторон отверстия
if ($brick[0] < $hole[0] && $brick[1] < $hole[1]) {
    echo "Результат: Кирпич пройдёт через отверстие.";
} else {
    echo "Результат: Кирпич не пройдёт через отверстие.";
