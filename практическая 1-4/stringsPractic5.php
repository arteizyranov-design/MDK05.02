Следующие задачи нужно решить без использования функций php для строк.

Можно использовать только функцию strlen().

Используйте строки на англйском языке.

Задание 1.

Дана строка символов, среди которых есть одна открывающаяся

и одна закрывающаяся скобка. Вывести на экран все символы,

расположенные внутри этих скобок.

Задание 2.

Дана строка, заканчивающаяся точкой. Подсчитать, сколько

слов в строке.

Задание 3

Дана строка. Найти в ней те слова, которые начинаются и

оканчиваются одной и той же буквой. Вывести эти слова на экран.

Задание 4

Дана строка. Подсчитать, сколько различных символов встречается в ней. Вывести их на экран.

Задание 5

Дана строка. Подсчитать, сколько в ней букв r, k, t.

Задание 6

Дана строка. Сделайте функцию, которая принимает параметром эту строку и возвращает новую строку, в которой удалены лишние пробелы из исходной строки если они есть. (пробелы в начале и конце строки, а также повторяющиеся пробелы внутри).

Задание 7

Дана строка, содержащая текст. Найти длину самого короткого слова и самого длинного слова.

Задание 8

Дана строка. Подсчитать самую длинную последовательность подряд идущих букв а.

Дополнительно:

Задание 9

Удалить часть символьной строки, заключенной в скобки (вместе со скобками).

Задине 10.

Вводите строки из форм. Сделайте функции для всех заданий.